#!/usr/bin/env bash
# expose-workers.sh — expose every vLLM/SGLang worker pod via a single
# NLB hostname, with the same offset-port scheme that scripts/port-forward.sh
# uses for localhost. Useful when running kinference (or any consumer that
# needs ZMQ + HTTP per-pod) locally, where `kubectl port-forward` is too
# flaky for sustained traffic.
#
# Architecture:
#
#     laptop ─► NLB:8000 ─► router-pod:8000  ─► vllm-pod-0:8000   (HTTP)
#     laptop ─► NLB:5557 ─► router-pod:5557  ─► vllm-pod-0:5557   (ZMQ PUB)
#     laptop ─► NLB:5558 ─► router-pod:5558  ─► vllm-pod-0:5558   (ZMQ ROUTER)
#     laptop ─► NLB:9000 ─► router-pod:9000  ─► vllm-pod-1:8000   (HTTP)
#     ... etc, up to 8 pods.
#
# The router pod is a thin nginx stream-proxy. Its config is generated
# from the CURRENT set of vLLM pod IPs at apply time. Pod restarts change
# pod IPs and stale the config — re-run `expose-workers regen` to
# regenerate without provisioning a new NLB.
#
# Subcommands:
#   up        Provision NLB Service + router Deployment + ConfigMap.
#             Idempotent — re-running with the same pod set is a no-op
#             after the initial apply.
#   regen     Just regenerate the router's nginx.conf from current
#             pods and bump the rollout. ~10s round-trip; no NLB touch.
#             Use after a vLLM pod restart.
#   down      Delete the NLB Service (polls AWS until LB is gone),
#             then the Deployment + ConfigMap.
#   endpoint  Wait for the NLB hostname to be assigned, then print one
#             URL line per (pod, port) — both the offset port mapping
#             and the per-pod IP it routes to.
#
# Required env (Makefile passes these):
#   CLUSTER_NAME, AWS_REGION, KUBECONFIG
#
# Optional:
#   MAX_SLOTS=8     Hard cap on exposed pods. Must match the slot count
#                   in the templates (worker-router-deployment.yaml.tmpl
#                   declares 8 named container ports). Don't change this
#                   without editing both templates.

set -euo pipefail

CLUSTER_NAME="${CLUSTER_NAME:-model-harness}"
AWS_REGION="${AWS_REGION:-us-west-2}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
TEMPLATES_DIR="${REPO_ROOT}/k8s/expose"

MAX_SLOTS="${MAX_SLOTS:-8}"

# Selector that picks just the inference worker pods (excludes
# agentgateway, kinference, llm-d EPP, etc.) — same shape we use in
# gen-monitor-config.sh.
WORKER_SELECTOR="mm/managed-by=model-harness,app.kubernetes.io/component=inference"

log()  { echo "▶  $*"; }
ok()   { echo "✓  $*"; }
skip() { echo "–  $*"; }
warn() { echo "⚠  $*" >&2; }

cmd="${1:-up}"

# ── Helpers ───────────────────────────────────────────────────────────────────

# emit_nginx_conf <slots-file>
#   Reads a TSV file of "<slot>\t<pod_name>\t<pod_ip>" lines on stdin
#   and emits a complete nginx.conf to stdout. Each slot produces three
#   stream{} server blocks at offset ports. Unfilled slots produce no
#   server block — connections to their listener port get TCP RST.
emit_nginx_conf() {
  cat <<'NGINX_HEADER'
# Auto-generated by aws-harness/scripts/expose-workers.sh.
# Re-run `make expose-workers-regen` after vLLM pod restarts.
worker_processes 1;
events { worker_connections 1024; }

stream {
  # Logs go to stdout so kubectl logs deploy/worker-router shows traffic.
  log_format basic '$remote_addr $protocol $server_port -> $upstream_addr '
                   '($status $bytes_sent ${session_time}s)';
  access_log /dev/stdout basic;
NGINX_HEADER

  while IFS=$'\t' read -r slot pod_name pod_ip; do
    [ -z "$slot" ] && continue
    local http=$((8000 + slot * 1000))
    local pub=$((5557 + slot * 1000))
    local rep=$((5558 + slot * 1000))
    cat <<NGINX_POD

  # Slot ${slot}: ${pod_name} @ ${pod_ip}
  server { listen ${http}; proxy_pass ${pod_ip}:8000; }
  server { listen ${pub};  proxy_pass ${pod_ip}:5557; }
  server { listen ${rep};  proxy_pass ${pod_ip}:5558; }
NGINX_POD
  done

  echo "}"
}

# discover_pods → outputs "<slot>\t<pod_name>\t<pod_ip>" per pod, sorted
# by (namespace, name) to match port-forward.sh's slot assignment.
discover_pods() {
  kubectl get pods \
    -l "${WORKER_SELECTOR}" \
    --field-selector=status.phase=Running \
    --all-namespaces \
    -o jsonpath='{range .items[*]}{.metadata.namespace}{"\t"}{.metadata.name}{"\t"}{.status.podIP}{"\n"}{end}' \
    2>/dev/null \
  | awk 'NF==3 && $3 != ""' \
  | sort -k1,1 -k2,2 \
  | awk -v max="${MAX_SLOTS}" 'NR<=max { print (NR-1) "\t" $2 "\t" $3 }'
}

# build_configmap_yaml → render worker-router-deployment.yaml.tmpl with
# the generated nginx.conf inlined and a fresh CONFIG_REVISION.
build_configmap_yaml() {
  local conf_indented
  # Indent every line of nginx.conf by 4 spaces so it fits under the
  # YAML `data.nginx.conf: |` block scalar.
  conf_indented=$(emit_nginx_conf | sed 's/^/    /')

  # CONFIG_REVISION is just a timestamp — used as a pod-template
  # annotation so re-applying with the same nginx.conf still triggers
  # a pod restart (otherwise the ConfigMap update wouldn't propagate
  # to the running nginx, since the mount is read-only).
  local rev
  rev=$(date -u +"%Y%m%d-%H%M%S")

  NGINX_CONF="${conf_indented}" CONFIG_REVISION="${rev}" \
    python3 -c "import os,sys; print(os.path.expandvars(sys.stdin.read()))" \
    < "${TEMPLATES_DIR}/worker-router-deployment.yaml.tmpl"
}

# ── Subcommands ───────────────────────────────────────────────────────────────

case "${cmd}" in

  up|regen)
    # Sanity check.
    if ! kubectl -n kube-system get deploy aws-load-balancer-controller \
         >/dev/null 2>&1; then
      warn "AWS Load Balancer Controller is not installed."
      warn "Run 'make install-lbc' first."
      exit 1
    fi

    # Discover current pods + assigned slots.
    SLOT_TSV=$(discover_pods)
    if [ -z "${SLOT_TSV}" ]; then
      warn "No running vLLM/SGLang pods found (selector: ${WORKER_SELECTOR})."
      warn "Deploy at least one server first:"
      warn "  make -f Makefile.server server-up CFG=servers/<name>.toml"
      exit 1
    fi

    POD_COUNT=$(echo "${SLOT_TSV}" | wc -l | tr -d ' ')
    log "Found ${POD_COUNT} worker pod(s) — assigning slots:"
    echo "${SLOT_TSV}" | awk -F'\t' \
      '{printf "      slot=%s  pod=%s  ip=%s\n", $1, $2, $3}'

    if [ "${POD_COUNT}" -gt "${MAX_SLOTS}" ]; then
      warn "Worker count (${POD_COUNT}) exceeds MAX_SLOTS (${MAX_SLOTS})."
      warn "Excess pods will not be reachable via the NLB."
      warn "Edit MAX_SLOTS in this script AND the slot count in both"
      warn "templates if you need more than ${MAX_SLOTS}."
    fi

    # Render + apply the ConfigMap + Deployment.
    log "Rendering router config + Deployment..."
    echo "${SLOT_TSV}" | (CONF=$(build_configmap_yaml); echo "${CONF}") \
      | kubectl apply -f -

    if [ "${cmd}" = "up" ]; then
      # Also apply the NLB Service. Idempotent — same listener set every time.
      OWNER_TAG="$(git config user.email 2>/dev/null || echo unknown)"
      log "Applying NLB Service (worker-router-public)..."
      OWNER_TAG="${OWNER_TAG}" \
        python3 -c "import os,sys; print(os.path.expandvars(sys.stdin.read()))" \
        < "${TEMPLATES_DIR}/worker-router-public.yaml.tmpl" \
        | kubectl apply -f -
    fi

    log "Waiting for router Deployment to roll..."
    kubectl -n default rollout status deploy/worker-router --timeout=2m
    ok "Router updated for ${POD_COUNT} worker pod(s)."

    if [ "${cmd}" = "up" ]; then
      echo ""
      echo "  Next:"
      echo "    make worker-nlb-host       # print the NLB hostname"
      echo "    make expose-workers-regen  # regenerate after pod restarts"
      echo "    make unexpose-workers      # tear it all down"
    fi
    ;;

  down)
    NLB_HOST=$(kubectl -n default get svc worker-router-public \
      -o jsonpath='{.status.loadBalancer.ingress[0].hostname}' 2>/dev/null \
      || echo "")

    if kubectl -n default get svc worker-router-public >/dev/null 2>&1; then
      log "Deleting svc/worker-router-public (forces NLB deletion)..."
      kubectl -n default delete svc worker-router-public --ignore-not-found
    fi

    if [ -n "${NLB_HOST}" ]; then
      log "Polling AWS until NLB '${NLB_HOST}' is fully deleted..."
      until [ -z "$(aws elbv2 describe-load-balancers \
              --region "${AWS_REGION}" \
              --query "LoadBalancers[?DNSName=='${NLB_HOST}'].LoadBalancerArn" \
              --output text 2>/dev/null)" ]; do
        printf '.'
        sleep 5
      done
      echo ""
      ok "NLB removed"
    fi

    log "Deleting router Deployment + ConfigMap..."
    kubectl -n default delete deploy worker-router --ignore-not-found
    kubectl -n default delete configmap worker-router-config --ignore-not-found
    ok "Worker exposure torn down."
    ;;

  endpoint)
    log "Waiting for worker-router-public NLB hostname..."
    until NLB_HOST=$(kubectl -n default get svc worker-router-public \
        -o jsonpath='{.status.loadBalancer.ingress[0].hostname}' 2>/dev/null) \
        && [ -n "${NLB_HOST}" ]; do
      printf '.'
      sleep 5
    done
    echo ""

    # Re-discover slots from the CURRENT router ConfigMap (not live pods).
    # The ConfigMap is what the router actually knows about. If pods have
    # changed since the last `up`/`regen`, those are the stale mappings
    # we want to print so the user can spot the divergence.
    log "Current slot map (from router ConfigMap):"
    kubectl -n default get cm worker-router-config \
      -o jsonpath='{.data.nginx\.conf}' \
      | awk '/^[[:space:]]+# Slot/ {sub(/^.*Slot /, ""); print "    " $0}'

    echo ""
    echo "  NLB hostname:"
    echo "    ${NLB_HOST}"
    echo ""
    echo "  Per-pod URL set (matching scripts/port-forward.sh's offset scheme):"
    for slot in 0 1 2 3 4 5 6 7; do
      http=$((8000 + slot * 1000))
      pub=$((5557 + slot * 1000))
      rep=$((5558 + slot * 1000))
      printf "    slot %d:  http://%s:%d/  zmq pub :%d  zmq rep :%d\n" \
        "${slot}" "${NLB_HOST}" "${http}" "${pub}" "${rep}"
    done
    echo ""
    echo "  Use the NLB for kinference config:"
    echo "    BASE_HOST=${NLB_HOST} bash scripts/gen-monitor-config.sh > config.toml"
    ;;

  *)
    echo "Usage: $0 {up|regen|down|endpoint}" >&2
    exit 1
    ;;
esac
